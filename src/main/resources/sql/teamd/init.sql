-- Mærker, fx Hunkemøller, Lindex og Triumph
CREATE TABLE teamd_brand
(
    brand_id SERIAL PRIMARY KEY,
    name     VARCHAR(100) NOT NULL UNIQUE
);

-- Hvert mærkes størrelsesguide: én række pr. størrelse (fx 75C)
CREATE TABLE teamd_size_guide
(
    size_guide_id    SERIAL PRIMARY KEY,
    brand_id         INT          NOT NULL REFERENCES teamd_brand (brand_id),
    band_size        INT          NOT NULL,
    cup_size         VARCHAR(4)   NOT NULL,
    size_system      VARCHAR(5)   NOT NULL,
    underbust_min_cm NUMERIC(5, 1) NOT NULL,
    underbust_max_cm NUMERIC(5, 1) NOT NULL,
    bust_min_cm      NUMERIC(5, 1) NOT NULL,
    bust_max_cm      NUMERIC(5, 1) NOT NULL,
    UNIQUE (brand_id, band_size, cup_size, size_system)
);

